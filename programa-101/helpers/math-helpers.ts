export function addTwoNumbers(number1: number, number2: number) {
    // console.log(number1 + number2);
    // Si no retornamos marcará undefined
    return number1 + number2;
}

export function substractTwoNumbers(number1: number, number2: number) {
    return number1 - number2;
}

export function multiplyTwoNumbers(number1: number, number2: number) {
    return number1 * number2;
}

export function divideTwoNumbers(number1: number, number2: number) {
    return number1 / number2;
}